def _parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="run_dataset.py",
        description=(
            "Run the SHAP-GSD pipeline (phases 01–14) against one or more "
            "NetFlow CSV files. Each CSV gets its own isolated run directory "
            "and experiment config so results never collide."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "Examples\n"
            "--------\n"
            "  # Full pipeline for one dataset:\n"
            "  python scripts/run_dataset.py --csv data/NF-UNSW-NB15-v3.csv\n\n"
            "  # Only pre-process and build the graph (phases 01–02):\n"
            "  python scripts/run_dataset.py --csv data/dataset01.csv "
            "--from-phase 1 --to-phase 2\n\n"
            "  # Apply a tuned config to a new dataset:\n"
            "  python scripts/run_dataset.py --csv data/NF-BoT-IoT-v3.csv "
            "--config-template configs/experiment_unsw.yaml\n\n"
            "  # Multiple datasets, skip tests, force config overwrite:\n"
            "  python scripts/run_dataset.py --csv data/a.csv data/b.csv "
            "--skip-tests --force-config "
            "--config-template configs/experiment_unsw.yaml\n"
        ),
    )

    parser.add_argument(
        "--csv",
        metavar="CSV",
        nargs="+",
        required=True,
        help=(
            "One or more paths to NetFlow CSV files. "
            "Each file is processed independently."
        ),
    )
    parser.add_argument(
        "--from-phase",
        metavar="N",
        type=int,
        default=1,
        help="First phase to execute (1–14, inclusive). Default: 1.",
    )
    parser.add_argument(
        "--to-phase",
        metavar="N",
        type=int,
        default=14,
        help="Last phase to execute (1–14, inclusive). Default: 14.",
    )
    parser.add_argument(
        "--skip-tests",
        action="store_true",
        default=False,
        help=(
            "Skip the pytest gate that normally runs after phase 02 completes. "
            "Not recommended for production runs."
        ),
    )
    parser.add_argument(
        "--skip-gateway-distance",
        action="store_true",
        default=False,
        help=(
            "Skip phase 14 (gateway-distance measurement) for this run, "
            "regardless of the topology.gateway_distance.enabled config value."
        ),
    )
    parser.add_argument(
        "--config-template",
        metavar="YAML",
        default=None,
        help=(
            "Experiment config whose settings are merged into the generated "
            "per-dataset config. The template is parsed and EVERY key it "
            "defines is carried over; only data.csv_path and run.dir are "
            "replaced with this run's values, so sibling keys such as "
            "data.train_frac survive. Applies ONLY when the per-dataset "
            "config is freshly written — an existing "
            "configs/experiment_<run_id>.yaml always wins (pass "
            "--force-config together with a template to rewrite it). "
            "Default: none, meaning the generated config overrides only "
            "data.csv_path / run.dir and every other setting comes from "
            "configs/default.yaml."
        ),
    )
    parser.add_argument(
        "--force-config",
        action="store_true",
        default=False,
        help=(
            "Overwrite an existing per-dataset experiment config. "
            "By default, existing configs are preserved (with a warning) "
            "so that manual edits survive re-runs. "
            "Requires --config-template when the target config already exists: "
            "overwriting a tuned config with a two-key stub is refused."
        ),
    )
    parser.add_argument(
        "--allow-bare-config",
        action="store_true",
        default=False,
        help=(
            "Proceed even when the per-dataset config overrides nothing "
            "beyond data and run — i.e. when every balancer, model and "
            "reproducibility setting comes from configs/default.yaml. "
            "Without this flag such a config aborts the dataset before phase "
            "01 (see specs/30). A config the orchestrator itself generated "
            "without a template is already exempt and does not need this "
            "flag. Use only when defaults-everything is genuinely intended."
        ),
    )

    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = _parse_args(argv)

    # Validate phase range — allow any positive integer; values beyond the
    # pipeline range (1–14) simply produce an empty phase selection (no-op).
    if args.from_phase < 1:
        log.error("--from-phase must be >= 1 (got %d).", args.from_phase)
        return 1
    if args.to_phase < 1:
        log.error("--to-phase must be >= 1 (got %d).", args.to_phase)
        return 1
    if args.from_phase > args.to_phase:
        log.warning(
            "--from-phase (%d) > --to-phase (%d): no phases will run.",
            args.from_phase,
            args.to_phase,
        )

    # Resolve and validate every CSV path up front (fail fast).
    csv_paths: list[Path] = []
    for raw in args.csv:
        p = Path(raw)
        if not p.is_absolute():
            p = REPO_ROOT / p
        if not p.exists():
            log.error("CSV not found: %s", p)
            return 1
        csv_paths.append(p)

    total = len(csv_paths)
    any_failed = False

    for idx, csv_path in enumerate(csv_paths, start=1):
        ok = run_dataset(
            csv_path=csv_path,
            dataset_index=idx,
            total_datasets=total,
            from_phase=args.from_phase,
            to_phase=args.to_phase,
            skip_tests=args.skip_tests,
            skip_gateway_distance=args.skip_gateway_distance,
            force_config=args.force_config,
            config_template=(
                Path(args.config_template) if args.config_template else None
            ),
            allow_bare_config=args.allow_bare_config,
        )
        if not ok:
            log.error("Dataset %d/%d FAILED: %s", idx, total, csv_path)
            any_failed = True
            # Continue to the next dataset rather than aborting the whole run.

    if any_failed:
        log.error("One or more datasets failed. See messages above.")
        return 1

    log.info("All datasets completed successfully.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
