def derive_run_id(csv_path: Path) -> str:
    """Derive a clean identifier from a CSV basename.

    Steps:
      1. Strip the ``.csv`` suffix (case-insensitive).
      2. Lowercase.
      3. Replace every run of non-alphanumeric characters with a single ``_``.
      4. Strip leading/trailing underscores.

    Examples::

        NF-UNSW-NB15-v3.csv  →  nf_unsw_nb15_v3
        dataset 01.csv        →  dataset_01
    """
    stem = csv_path.stem  # removes final suffix only (.csv)
    run_id = stem.lower()
    run_id = re.sub(r"[^a-z0-9]+", "_", run_id)
    run_id = run_id.strip("_")
    return run_id


def _now_iso() -> str:
    """Return the current local time as a second-resolution ISO-8601 string."""
    return datetime.datetime.now().astimezone().isoformat(timespec="seconds")


def _top_level_keys(cfg_path: Path) -> set[str]:
    """Parse ``cfg_path`` and return its top-level YAML mapping keys.

    An empty document (``yaml.safe_load`` returns ``None``) yields an empty
    set. Used by the bare-stub guard, which asks whether the file overrides
    anything at all beyond ``data``/``run``.

    Raises
    ------
    ConfigMaterializationError
        If the file is unreadable, is not valid YAML, or does not parse to a
        mapping. Degrading to "assume it is fine" here would let a corrupt
        config reach 14 phases of compute.
    """
    try:
        parsed = yaml.safe_load(cfg_path.read_text())
    except (yaml.YAMLError, OSError) as exc:
        raise ConfigMaterializationError(
            f"Per-dataset config {cfg_path} could not be read or parsed: {exc}. "
            f"Refusing to proceed on an unreadable config. "
            f"Nothing was modified on disk."
        ) from exc
    if parsed is None:
        return set()
    if not isinstance(parsed, dict):
        raise ConfigMaterializationError(
            f"Per-dataset config {cfg_path} is not a YAML mapping (parsed as "
            f"{type(parsed).__name__}). An experiment config must be a "
            f"top-level mapping. Nothing was modified on disk."
        )
    return set(parsed)


def _has_no_template_marker(cfg_path: Path) -> bool:
    """Return *True* if the file's comment header records the no-template ack.

    YAML comments are invisible to ``yaml.safe_load``, so this is a raw-text
    scan: a line whose first non-whitespace character is ``#`` and which
    contains ``NO_TEMPLATE_MARKER``. Restricting the scan to comment lines
    keeps a YAML *value* that happens to contain the sentinel (e.g. a path)
    from forging an acknowledgement.

    Fails closed: an unreadable file returns *False*, so the guard fires.
    """
    try:
        text = cfg_path.read_text()
    except OSError:
        return False
    return any(
        line.lstrip().startswith("#") and NO_TEMPLATE_MARKER in line
        for line in text.splitlines()
    )


def _guard_bare_stub_keys(
    *,
    keys: set[str],
    has_marker: bool,
    cfg_path: Path,
    origin: str,
    allow_bare_config: bool,
    csv_hint: str = "<dataset.csv>",
) -> None:
    """Decision core of the bare-stub guard, on already-extracted evidence.

    Split out of :func:`_guard_bare_stub` so the guard can also run on an
    IN-MEMORY merged mapping, BEFORE anything is written to disk. Guarding only
    the written file made the refusal destructive: ``--force-config`` with a
    stub-shaped template overwrote a tuned config and only then aborted, while
    the refusal message still promised "Nothing was modified on disk".

    Parameters
    ----------
    keys:
        Top-level key set of the config being judged (parsed from a file, or
        ``set(merged)`` for a not-yet-written mapping).
    has_marker:
        Whether the config carries the ``NO_TEMPLATE_MARKER`` acknowledgement.
        Always *False* for a template-derived write: that header is generated
        here and never contains the marker.
    cfg_path:
        Used for messaging ONLY — never read, never written by this function.
    origin:
        Human-readable provenance quoted in the refusal message.
    allow_bare_config:
        When *True*, downgrade the refusal to a WARNING and return.
    csv_hint:
        Dataset CSV quoted in the remediation command line.

    Raises
    ------
    ConfigMaterializationError
        When the guard fires and ``allow_bare_config`` is *False*.
    """
    if not keys <= BARE_STUB_KEYS:
        return
    if has_marker:
        log.info(
            "Config %s is a defaults-only overlay, and records the "
            "'%s' acknowledgement in its header — proceeding.",
            cfg_path,
            NO_TEMPLATE_MARKER,
        )
        return
    if allow_bare_config:
        log.warning(
            "--allow-bare-config set: proceeding with the defaults-only config %s "
            "(%s). Every balancer/model/reproducibility setting for this run comes "
            "from configs/default.yaml.",
            cfg_path,
            origin,
        )
        return
    raise ConfigMaterializationError(
        _BARE_STUB_MESSAGE.format(
            cfg_path=cfg_path,
            keys=", ".join(sorted(keys)) or "(nothing at all)",
            origin=origin,
            csv_hint=csv_hint,
        )
    )


def _guard_bare_stub(
    cfg_path: Path,
    *,
    origin: str,
    allow_bare_config: bool,
    csv_hint: str = "<dataset.csv>",
) -> None:
    """Refuse to proceed with a config ON DISK that overrides nothing meaningful.

    Fires when the parsed top-level key set is a subset of ``BARE_STUB_KEYS``
    and the file carries no ``NO_TEMPLATE_MARKER`` acknowledgement. This is the
    signature of the damaged ``configs/experiment_nf_unsw_nb15_v3.yaml``
    (specs/30 §1.4) and of a ``--config-template`` mistakenly pointed at a
    stub-shaped file.

    Parameters
    ----------
    cfg_path:
        The per-run config to inspect.
    origin:
        Human-readable provenance for the message -- ``"pre-existing on disk"``
        or ``"generated from template <path>"``. Named so the error tells the
        user which of the two situations they are in.
    allow_bare_config:
        When *True*, downgrade the refusal to a WARNING and return.
    csv_hint:
        The dataset CSV to quote in the remediation command line. Supplied by
        the caller rather than read back out of ``cfg_path``: the guard also
        fires on key sets that do not contain ``data`` at all (an empty or
        ``{run}``-only document), where the file has no csv path to read.

    Raises
    ------
    ConfigMaterializationError
        When the guard fires and ``allow_bare_config`` is *False*.

    Known limitation (specs/30 §5): the key-set signature is a heuristic. A
    hand-written config that legitimately overrides only ``data`` and ``run``
    trips it; ``--allow-bare-config`` is the intended escape hatch. Keying on
    the ``# Auto-generated`` header instead was rejected -- it would
    false-NEGATIVE the moment a user hand-edits the file.

    This reads ``cfg_path`` (parsed keys + raw-text marker scan) and delegates
    the verdict to :func:`_guard_bare_stub_keys`. It never writes or deletes.
    """
    _guard_bare_stub_keys(
        keys=_top_level_keys(cfg_path),
        has_marker=_has_no_template_marker(cfg_path),
        cfg_path=cfg_path,
        origin=origin,
        allow_bare_config=allow_bare_config,
        csv_hint=csv_hint,
    )


def materialize_config(
    csv_path: Path,
    run_dir: Path,
    run_id: str,
    force: bool,
    template: Path | None = None,
    allow_bare_config: bool = False,
) -> Path:
    """Produce ``configs/experiment_<run_id>.yaml`` and return its path.

    Precedence, highest last (specs/31 §I.2)::

        configs/default.yaml  <  template  <  this run's csv_path / run.dir

    ``template`` is parsed with ``yaml.safe_load`` and this run's
    ``data.csv_path`` / ``run.dir`` are deep-merged OVER it, so the template's
    own copies of those two keys are replaced while every other key it defines
    -- including sibling ``data.*`` keys such as ``train_frac`` -- survives
    untouched. The result is written as a SELF-CONTAINED YAML: the per-run
    config is a reproducibility artifact and must answer "what settings
    produced this run" on its own, without a template chain (specs/30 §2).

    An existing ``configs/experiment_<run_id>.yaml`` always wins over a
    template unless ``force`` is set -- the HPC PBS jobs pre-populate this file
    and pass no template (specs/30 §4).

    Tradeoff, accepted deliberately: ``yaml.safe_dump`` DISCARDS the template's
    comments, and in this repo those comments are load-bearing rationale
    ("caps Worms(~2820->50)", "trial 48 was the only tuning trial where
    Backdoor converged"). The generated file therefore opens with a provenance
    header naming the template it came from. Preserving comments would need
    ``ruamel.yaml``, which is not in requirements.txt and is out of scope
    (specs/30 §2.1).

    Parameters
    ----------
    csv_path:
        Path to the input CSV (stored repo-relative when possible so it
        resolves from the repo root, matching how existing configs work).
    run_dir:
        Destination run directory (e.g. ``runs/nf_unsw_nb15_v3``).
    run_id:
        Sanitised dataset identifier.
    force:
        When *True*, overwrite an existing config file. Requires ``template``
        whenever the target already exists (see Raises).
    template:
        Optional experiment config whose settings are carried into the
        generated file. *None* means defaults-only, which is allowed but
        warned about loudly and recorded in the generated file's header.
    allow_bare_config:
        When *True*, downgrade the bare-stub refusal to a warning.

    Returns
    -------
    Path
        Absolute path to the written (or pre-existing) config file.

    Raises
    ------
    ConfigMaterializationError
        If ``template`` is given but missing / unparseable / not a mapping; if
        ``force`` is set without a template against an existing file; or if the
        resulting config is a bare stub without a recorded acknowledgement.
    """
    configs_dir = REPO_ROOT / "configs"
    cfg_path = configs_dir / f"experiment_{run_id}.yaml"

    # Make csv_path relative to repo root when possible (mirrors existing configs).
    # NOTE: Do NOT call .resolve() on csv_path — the repo's data/ directory is a
    # symlink and resolving it would produce a path outside REPO_ROOT, which then
    # cannot be made relative.  csv_path is already absolute at this point (the
    # caller constructs it as REPO_ROOT / user_arg before existence-checking).
    try:
        csv_rel = csv_path.relative_to(REPO_ROOT)
    except ValueError:
        # csv_path is outside the repo (e.g. absolute path to a network share).
        csv_rel = csv_path

    # NOTE: str() is REQUIRED — yaml.safe_dump raises RepresenterError on a
    # PosixPath. The old code stringified implicitly via an f-string; the
    # parse->merge->dump path does not.
    injection: dict = {
        "data": {"csv_path": str(csv_rel)},
        "run": {"dir": str(run_dir)},
    }

    # --- (c) PRESERVE-EXISTING ------------------------------------------------
    if cfg_path.exists() and not force:
        log.warning(
            "Config already exists — skipping write to preserve user edits: %s"
            "  (pass --force-config WITH --config-template to rewrite it)",
            cfg_path,
        )
        if template is not None:
            log.warning(
                "--config-template %s was NOT applied: the existing config %s "
                "wins (specs/30 §4). Delete it, or pass --force-config, to "
                "rewrite from the template.",
                template,
                cfg_path,
            )
        _guard_bare_stub(
            cfg_path,
            origin="pre-existing on disk",
            allow_bare_config=allow_bare_config,
            csv_hint=str(csv_rel),
        )
        return cfg_path

    # --- (d) FORCE WITHOUT TEMPLATE, against an existing file ------------------
    if cfg_path.exists() and force and template is None:
        raise ConfigMaterializationError(
            f"--force-config was passed without --config-template, and "
            f"{cfg_path} already exists. Overwriting it would replace its "
            f"contents with a two-key stub, silently reverting every tuned "
            f"setting to configs/default.yaml — and would additionally stamp "
            f"the '{NO_TEMPLATE_MARKER}' acknowledgement into the result, "
            f"permanently exempting it from the bare-stub guard.\n"
            f"Pass --config-template <tuned.yaml> to rewrite from a template, "
            f"or delete {cfg_path} manually if a defaults-only config really "
            f"is what you want regenerated.\n"
            f"Nothing was modified on disk."
        )

    # --- (e) TEMPLATE LOAD ----------------------------------------------------
    if template is not None:
        tpl_path = template if template.is_absolute() else REPO_ROOT / template
        if not tpl_path.is_file():
            raise ConfigMaterializationError(
                f"--config-template not found: {tpl_path} (given as "
                f"'{template}'). Refusing to fall back to a defaults-only "
                f"config — silently applying configs/default.yaml while you "
                f"believe a tuned template is in force is exactly the bug this "
                f"flag exists to prevent (specs/30 §1.4). "
                f"Nothing was modified on disk."
            )
        try:
            parsed = yaml.safe_load(tpl_path.read_text())
        except (yaml.YAMLError, OSError) as exc:
            raise ConfigMaterializationError(
                f"--config-template {tpl_path} could not be parsed: {exc}"
            ) from exc
        # An EMPTY template parses to None. That is not an error here — it
        # produces a bare result, which the guard at (f0) catches — before any
        # write — with a much more useful message than a parse error would give.
        tpl: dict = parsed or {}
        if not isinstance(tpl, dict):
            raise ConfigMaterializationError(
                f"--config-template {tpl_path} is not a YAML mapping (parsed "
                f"as {type(parsed).__name__}). An experiment config must be a "
                f"top-level mapping. Nothing was modified on disk."
            )
        merged = _deep_merge(tpl, injection)
        header_lines = [
            f"# Auto-generated by scripts/run_dataset.py on {_now_iso()}",
            f"# Derived from template: {template}",
            "# Comments from the template are NOT preserved by the YAML "
            "round-trip —",
            "# read that file for the rationale behind these values.",
            "# data.csv_path and run.dir below are THIS run's values and "
            "override the template's.",
        ]
    else:
        merged = copy.deepcopy(injection)
        header_lines = [
            f"# Auto-generated by scripts/run_dataset.py on {_now_iso()}",
            f"# {NO_TEMPLATE_MARKER}: generated without --config-template.",
            "# Defaults-only run: every setting outside data.csv_path and "
            "run.dir",
            "# comes from configs/default.yaml. Pass --config-template "
            "<tuned.yaml>",
            "# (after deleting this file) to apply a tuned configuration "
            "instead.",
        ]

    # --- (f0) PRE-WRITE GUARD — fresh-write-with-template only ----------------
    # Deliberate deviation from specs/31 §I.3.7(h)/§I.3.8, which placed this
    # AFTER the write: guarding the written file made the refusal DESTRUCTIVE.
    # `--force-config` with a stub-shaped (or empty) template overwrote an
    # existing tuned config with a two-key stub and only then aborted — while
    # the refusal message promised "Nothing was modified on disk". Judging the
    # in-memory `merged` mapping keeps that promise true on every abort path.
    # Top-level keys round-trip unchanged through safe_dump/safe_load, so
    # set(merged) is exactly what the post-write check would have seen.
    #
    # The no-template branch is exempt by construction (its header carries
    # NO_TEMPLATE_MARKER); has_marker=False below is therefore correct for the
    # template branch, whose generated header never contains the marker.
    if template is not None:
        _guard_bare_stub_keys(
            keys=set(merged),
            has_marker=False,
            cfg_path=cfg_path,
            origin=f"generated from template {template}",
            allow_bare_config=allow_bare_config,
            csv_hint=str(csv_rel),
        )

    # --- (f) WRITE ------------------------------------------------------------
    if cfg_path.exists() and force:
        log.info("--force-config set; overwriting existing config: %s", cfg_path)
    body = yaml.safe_dump(
        merged,
        sort_keys=False,          # preserve the template's own key order —
                                  # keeps generated configs diffable
        default_flow_style=False,
        allow_unicode=True,
    )
    cfg_path.write_text("\n".join(header_lines) + "\n" + body)
    log.info("Wrote config: %s", cfg_path)
    if template is not None:
        log.info(
            "  inherited from template: %s (top-level sections: %s)",
            template,
            ", ".join(sorted(merged)),
        )
    log.info("  injected data.csv_path = %s", injection["data"]["csv_path"])
    log.info("  injected run.dir       = %s", injection["run"]["dir"])

    # --- (g) NO-TEMPLATE WARNING ----------------------------------------------
    if template is None:
        effective = load_config(cfg_path)
        log.warning(
            "No --config-template supplied: %s overrides ONLY data.csv_path "
            "and run.dir. Every other setting comes from configs/default.yaml, "
            "including balancer.class_weight_method=%r, "
            "reproducibility.model_seed=%r, model.early_stopping_metric=%r, "
            "model.patience=%r. If this dataset has a tuned config, delete "
            "this file and re-run with --config-template <that file>; "
            "otherwise hand-edit it (it is preserved on re-run).",
            cfg_path,
            effective.get("balancer", {}).get("class_weight_method"),
            effective.get("reproducibility", {}).get("model_seed"),
            effective.get("model", {}).get("early_stopping_metric"),
            effective.get("model", {}).get("patience"),
        )

    # (h) The bare-stub guard for this path ran at (f0), BEFORE the write.
    return cfg_path


def log_resolved_config(cfg_path: Path) -> None:
    """Log the FULL merged effective config at INFO before any phase runs.

    Loads ``cfg_path`` through the real ``load_config`` -- the same call every
    phase script makes -- so what is logged is what the pipeline will actually
    use, defaults included. This is the audit trail for a batch run: a
    log-reader can see every effective setting without a checkout and without
    reasoning about which keys the experiment file happened to omit.

    Emits, in order: the config path and the default it was merged over; a
    one-line caveat about run.dir prefixing; a digest of KEY_SETTINGS_DIGEST;
    then the complete merged mapping as YAML, one log record per line.
    """
    cfg = load_config(cfg_path)
    _banner("Effective configuration (merged) — inspect before phase 01")
    log.info("Experiment config : %s", cfg_path)
    log.info("Merged over       : %s", cfg_path.parent / "default.yaml")
    log.info(
        "NOTE: output/graph/topology paths below are shown AFTER run.dir "
        "prefixing (src/utils/config.py::_apply_run_dir_prefix), so they will "
        "not match the on-disk file's text. This is expected."
    )
    log.info("Key settings:")
    for dotted in KEY_SETTINGS_DIGEST:
        node: object = cfg
        for part in dotted.split("."):
            node = node.get(part, _ABSENT) if isinstance(node, dict) else _ABSENT
            if node is _ABSENT:
                break
        log.info(
            "  %-38s = %s", dotted, "<absent>" if node is _ABSENT else repr(node)
        )
    log.info("Full merged config:")
    for line in yaml.safe_dump(
        cfg, sort_keys=False, default_flow_style=False, allow_unicode=True
    ).splitlines():
        log.info("  %s", line)


def run_phase(
    script_name: str,
    label: str,
    phase_num: int,
    cfg_path: Path,
    env: dict[str, str] | None = None,
) -> bool:
    """Invoke a single pipeline script, streaming its output to the console.

    Parameters
    ----------
    script_name:
        Filename within ``scripts/`` (e.g. ``"01_preprocess.py"``).
    label:
        Human-readable description for log messages.
    phase_num:
        Integer phase number for the banner.
    cfg_path:
        Absolute path to the per-dataset config YAML.
    env:
        Optional extra environment variables merged over the current env.

    Returns
    -------
    bool
        *True* if the script exited cleanly (returncode 0), *False* otherwise.
    """
    _banner(f"Phase {phase_num:02d}: {label}")
    script = REPO_ROOT / "scripts" / script_name
    cmd = [sys.executable, str(script), "--config", str(cfg_path)]

    proc_env = os.environ.copy()
    if env:
        proc_env.update(env)

    result = subprocess.run(cmd, cwd=str(REPO_ROOT), env=proc_env)
    if result.returncode != 0:
        log.error(
            "Phase %02d (%s) FAILED with exit code %d.",
            phase_num,
            label,
            result.returncode,
        )
        return False

    log.info("Phase %02d (%s) completed successfully.", phase_num, label)
    return True


def run_pytest_gate(cfg_path: Path) -> bool:
    """Run the pytest test suite (gate after phase 02).

    The ``SHAP_GSD_CONFIG`` environment variable is set so tests can locate the
    correct per-dataset config (Phase C convention).

    Returns
    -------
    bool
        *True* if all tests passed, *False* otherwise.
    """
    _banner("pytest gate (post-phase-02)")
    cmd = [sys.executable, "-m", "pytest", "tests/", "-v", "-x"]
    proc_env = os.environ.copy()
    proc_env["SHAP_GSD_CONFIG"] = str(cfg_path)

    result = subprocess.run(cmd, cwd=str(REPO_ROOT), env=proc_env)
    if result.returncode != 0:
        log.error("pytest gate FAILED — aborting this dataset's run.")
        return False

    log.info("pytest gate passed.")
    return True


