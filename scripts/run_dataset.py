# A generated config whose parsed top-level key set is a SUBSET of this is
# "bare": it overrides nothing, so every balancer/model/reproducibility setting
# silently comes from configs/default.yaml. This is the exact shape of the
# damaged configs/experiment_nf_unsw_nb15_v3.yaml (specs/30 §1.4).
BARE_STUB_KEYS: frozenset[str] = frozenset({"data", "run"})

# Sentinel written into the generated file's comment header ONLY when the file
# was generated with no --config-template, i.e. defaults-only was consciously
# chosen. The bare-stub guard treats it as a durable acknowledgement so a
# legitimate defaults-only dataset survives re-invocation (--from-phase 8,
# resume-after-failure) without --allow-bare-config (specs/30 §3.1).
#
# It must NOT collide with the legacy header of the already-damaged file,
# "# Auto-generated by scripts/run_dataset.py - edit only if you know what
# you're doing." -- that header carries no such sentinel, so the damaged file
# still trips the guard. Detection is a raw-text scan of comment lines (YAML
# comments are invisible to yaml.safe_load), and it fails CLOSED: stripping or
# hand-editing the marker line re-arms the guard.
NO_TEMPLATE_MARKER: str = "NO-TEMPLATE-ACKNOWLEDGED"

# Keys surfaced in the pre-phase "key settings" digest (specs/31 §I.4).
# Dotted paths, resolved against the MERGED config. Order is display order.
KEY_SETTINGS_DIGEST: tuple[str, ...] = (
    "data.csv_path",
    "data.train_frac",
    "data.val_frac",
    "run.dir",
    "seed",
    "reproducibility.model_seed",
    "balancer.strategy",
    "balancer.class_weight_method",
    "balancer.class_weight_max_clamp",
    "balancer.effective_num_beta",
    "model.early_stopping_metric",
    "model.patience",
    "model.max_epochs",
    "model.minority_class_threshold",
    "model.composite_minority_weight",
    "model.hidden_size",
    "model.fanouts",
    "model.learning_rate",
)

# Sentinel distinguishing "key absent" from "key present with value None" in
# the KEY_SETTINGS_DIGEST walk.
_ABSENT = object()

# Refusal message for the bare-stub guard. Kept module-level so tests can
# assert on stable substrings.
_BARE_STUB_MESSAGE = (
    "Per-dataset config {cfg_path} defines nothing beyond {keys} ({origin}).\n"
    "Every balancer, model and reproducibility setting for this run would silently\n"
    "come from configs/default.yaml — including class_weight_method, model_seed,\n"
    "early_stopping_metric and patience. This is the exact failure documented in\n"
    "specs/30 §1.4, which already produced one run with the wrong class weights.\n"
    "Remedies (pick one):\n"
    "  * apply a tuned config — point --config-template at a REAL tuned file:\n"
    "      python scripts/run_dataset.py --csv {csv_hint} "
    "--config-template <tuned.yaml>\n"
    "    (if {cfg_path} exists and is itself the bare config, delete it first,\n"
    "     or add --force-config so the template rewrites it)\n"
    "  * hand-edit {cfg_path} to add the settings this dataset needs, then re-run\n"
    "  * if defaults-everything is genuinely intended for this dataset, re-run with\n"
    "    --allow-bare-config (the choice is then recorded on the command line)\n"
    "Aborting this dataset before phase 01. Nothing was modified on disk."
)


class ConfigMaterializationError(RuntimeError):
    """Raised when the per-dataset config cannot be safely produced or used.

    Carries a fully-formed, user-facing remediation message; ``run_dataset``
    catches it, logs ``str(exc)`` at ERROR and fails that dataset BEFORE any
    phase subprocess is launched.
    """


