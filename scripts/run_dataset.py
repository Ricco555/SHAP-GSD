"""Orchestrator: run the full SHAP-GSD pipeline against one or more NetFlow CSVs.

Usage
-----
    python scripts/run_dataset.py --csv data/dataset01.csv [data/dataset02.csv ...]
                                  [--from-phase 01] [--to-phase 14]
                                  [--skip-tests] [--skip-gateway-distance]
                                  [--config-template YAML] [--force-config]
                                  [--allow-bare-config]

For each CSV the orchestrator
  1. Derives a ``run_id`` from the basename.
  2. Creates ``runs/<run_id>/``.
  3. Materialises ``configs/experiment_<run_id>.yaml``. With
     ``--config-template`` the template is parsed and every key it defines is
     carried into the generated file, with only ``data.csv_path`` and
     ``run.dir`` replaced by this run's values. Without a template the
     generated file is a two-key overlay and every other setting comes from
     ``configs/default.yaml`` -- which is loudly warned about, and recorded in
     the generated file's header.
  4. Refuses to proceed when the per-dataset config on disk defines nothing
     beyond ``data`` and ``run`` without that recorded acknowledgement
     (``--allow-bare-config`` overrides). See specs/30 and specs/31.
  5. Logs the FULL merged effective config at INFO, before the first phase.
  6. Invokes pipeline scripts 01-14 (or the requested sub-range) in order,
     streaming output directly to the console.
  7. Optionally runs the pytest gate after phase 02.
"""

