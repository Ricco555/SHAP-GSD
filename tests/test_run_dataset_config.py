def test_resolved_config_is_logged_at_info_before_any_phase_runs(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Devops 2 — ORDERING, not mere presence.

    Log records and subprocess launches are appended to ONE shared list, so the
    assertion is that the effective-config records appear strictly BEFORE the
    first phase subprocess. Asserting on two separate lists would only prove
    "both happened", which does not discharge "before Phase 1 starts".
    """
    repo_root, _ = _fake_repo(tmp_path, monkeypatch)
    tpl = tmp_path / "tuned.yaml"
    _tuned_template(tpl)

    events: list = []
    handler = _SharedListHandler(events)
    logger = logging.getLogger("run_dataset")
    logger.addHandler(handler)
    monkeypatch.setattr(logger, "level", logging.INFO, raising=False)
    _no_subprocess(monkeypatch, sink=events)
    try:
        ok = MOD.run_dataset(
            csv_path=repo_root / "data" / "mydataset.csv",
            dataset_index=1,
            total_datasets=1,
            from_phase=1,
            to_phase=1,
            skip_tests=True,
            skip_gateway_distance=False,
            force_config=False,
            config_template=tpl,
        )
    finally:
        logger.removeHandler(handler)

    assert ok is True
    proc_indices = [i for i, (kind, _) in enumerate(events) if kind == "proc"]
    assert len(proc_indices) == 1, "expected exactly one phase subprocess"
    first_proc = proc_indices[0]

    def _first_log_index(needle: str) -> int:
        for i, (kind, payload) in enumerate(events):
            if kind == "log" and needle in payload:
                return i
        raise AssertionError(f"{needle!r} never logged; events={events}")

    # Needles are specific enough that only the merged-config dump can supply
    # them — a bare "90" would match a timestamp or path fragment instead.
    for needle in (
        "inverse_freq",
        "early_stopping_metric: composite",
        "model_seed: 90",
        "data/mydataset.csv",
    ):
        assert _first_log_index(needle) < first_proc


