def test_key_settings_digest_marks_absent_keys(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, caplog: pytest.LogCaptureFixture
) -> None:
    """Devops 2 — the digest degrades gracefully, and ``None`` is not ``<absent>``.

    Part 1 uses a MINIMAL ``default.yaml`` (no ``model:`` section at all), so a
    digest key really is missing — with the real defaults every one of the 18
    dotted paths resolves and the assertion would be vacuous. Part 2 pins the
    ``_ABSENT`` sentinel's whole reason to exist: ``class_weight_max_clamp`` is
    ``null`` in the real defaults and must log ``None``, NOT ``<absent>``.
    """
    # --- Part 1: an absent key is reported, not raised on. -------------------
    minimal_configs = tmp_path / "minimal_configs"
    minimal_configs.mkdir()
    (minimal_configs / "default.yaml").write_text(
        "data:\n  csv_path: 'x.csv'\nrun:\n  dir: ''\nseed: 42\n"
    )
    minimal_cfg = minimal_configs / "experiment_minimal.yaml"
    minimal_cfg.write_text("data:\n  csv_path: 'y.csv'\n")

    caplog.set_level(logging.INFO, logger="run_dataset")
    MOD.log_resolved_config(minimal_cfg)

    messages = [r.getMessage() for r in caplog.records]
    assert _digest_line(messages, "model.patience").endswith("<absent>")
    assert _digest_line(messages, "data.train_frac").endswith("<absent>")
    assert _digest_line(messages, "seed").endswith("42")

    # --- Part 2: an explicit null is reported as None, not <absent>. ---------
    caplog.clear()
    repo_root, _ = _fake_repo(tmp_path, monkeypatch)
    real_cfg = _materialize(repo_root, template=None)
    MOD.log_resolved_config(real_cfg)

    messages = [r.getMessage() for r in caplog.records]
    line = _digest_line(messages, "balancer.class_weight_max_clamp")
    assert line.endswith("None")
    assert "<absent>" not in line
