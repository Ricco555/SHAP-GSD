def test_top_level_keys_and_marker_helpers_are_independent(tmp_path: Path) -> None:
    """The two predicates answer different questions and fail differently.

    ``_top_level_keys`` parses (empty document → empty set; non-mapping →
    raises); ``_has_no_template_marker`` is a raw-text scan restricted to
    COMMENT lines, so the same sentinel appearing in a YAML *value* cannot
    forge an acknowledgement, and a missing file fails closed (*False*).
    """
    empty = tmp_path / "empty.yaml"
    empty.write_text("")
    assert MOD._top_level_keys(empty) == set()

    scalar = tmp_path / "scalar.yaml"
    scalar.write_text("42\n")
    with pytest.raises(MOD.ConfigMaterializationError):
        MOD._top_level_keys(scalar)

    marked = tmp_path / "marked.yaml"
    marked.write_text(f"# {MOD.NO_TEMPLATE_MARKER}: defaults only\ndata: {{}}\n")
    assert MOD._has_no_template_marker(marked) is True

    forged = tmp_path / "forged.yaml"
    forged.write_text(
        "data:\n"
        f'  csv_path: "data/{MOD.NO_TEMPLATE_MARKER}/x.csv"\n'
    )
    assert MOD._has_no_template_marker(forged) is False

    assert MOD._has_no_template_marker(tmp_path / "does_not_exist.yaml") is False


