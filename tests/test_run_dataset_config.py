def _load_orchestrator() -> types.ModuleType:
    """Import ``scripts/run_dataset.py`` as a module (it is a script, not a package).

    Loaded under a distinct ``sys.modules`` name so it cannot shadow anything,
    and cached at module scope: per-test ``monkeypatch.setattr`` on
    ``REPO_ROOT`` unwinds correctly against a single shared module object.
    """
    spec = importlib.util.spec_from_file_location(
        "run_dataset_under_test", REPO_ROOT / "scripts" / "run_dataset.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["run_dataset_under_test"] = module
    spec.loader.exec_module(module)
    return module


MOD = _load_orchestrator()


def _fake_repo(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> tuple[Path, Path]:
    """Build a throwaway repo root and point the orchestrator module at it.

    Creates ``tmp_path/configs/default.yaml`` as a byte copy of the REAL
    ``configs/default.yaml`` — the tuned-value assertions are only meaningful
    when compared against the real defaults — plus ``tmp_path/data/``, and
    monkeypatches ``MOD.REPO_ROOT``. Patching ``REPO_ROOT`` also redirects
    ``run_dataset``'s ``runs/<run_id>/`` mkdir away from the checkout.

    Returns
    -------
    tuple[Path, Path]
        ``(repo_root, configs_dir)``.
    """
    configs_dir = tmp_path / "configs"
    configs_dir.mkdir()
    shutil.copyfile(REAL_DEFAULT_YAML, configs_dir / "default.yaml")
    (tmp_path / "data").mkdir()
    monkeypatch.setattr(MOD, "REPO_ROOT", tmp_path)
    return tmp_path, configs_dir


def _tuned_template(path: Path) -> None:
    """Write a template carrying one distinctive non-default value per section.

    Every value differs from ``configs/default.yaml``, so an assertion that
    reads it back through ``load_config`` cannot pass by accident::

        data.csv_path                   "/lustre/other/OTHER.csv" (run-specific)
        data.train_frac                 0.55  (default: 0.6)
        data.val_frac                   0.25  (default: 0.3)
        run.dir                         "runs/other_ds"           (run-specific)
        balancer.class_weight_method    "inverse_freq" (default: "effective_num")
        balancer.class_weight_max_clamp 50    (default: null)
        reproducibility.model_seed      90    (default: 42)
        model.early_stopping_metric     "composite" (default: "macro_f1")
        model.patience                  20    (default: 10)
    """
    path.write_text(
        yaml.safe_dump(
            {
                "data": {
                    "csv_path": "/lustre/other/OTHER.csv",
                    "train_frac": 0.55,
                    "val_frac": 0.25,
                },
                "run": {"dir": "runs/other_ds"},
                "balancer": {
                    "class_weight_method": "inverse_freq",
                    "class_weight_max_clamp": 50,
                },
                "reproducibility": {"model_seed": 90},
                "model": {"early_stopping_metric": "composite", "patience": 20},
            },
            sort_keys=False,
        )
    )


def _seven_key_config(path: Path, *, marker: str = "tuned-on-disk") -> None:
    """Write a 7-key config with the shape of ``configs/experiment_unsw.yaml``.

    Top-level keys ``{data, run, preprocessing, balancer, reproducibility,
    model, seed}`` — also the shape of all eight HPC ``experiment_nf_*``
    configs, so this doubles as the "no PBS job trips the guard" fixture.
    """
    path.write_text(
        f"# {marker}\n"
        + yaml.safe_dump(
            {
                "data": {"csv_path": "/lustre/on-disk/ONDISK.csv"},
                "run": {"dir": "runs/on_disk"},
                "preprocessing": {"spearman_threshold": 0.99},
                "balancer": {"class_weight_method": "sqrt_inverse_freq"},
                "reproducibility": {"model_seed": 7},
                "model": {"patience": 33},
                "seed": 11,
            },
            sort_keys=False,
        )
    )


def _no_subprocess(
    monkeypatch: pytest.MonkeyPatch, sink: list | None = None
) -> list:
    """Replace ``subprocess.run`` with a recorder; return the call log.

    The fake returns an object exposing ``.returncode == 0`` because
    ``run_phase`` reads that attribute immediately. When ``sink`` is given the
    recorder appends into it, so log records and subprocess launches can share
    ONE list and their relative ORDER becomes assertable (specs/31 §I.8.3 D22).
    """
    calls: list = sink if sink is not None else []

    def _fake_run(cmd, *args, **kwargs):  # noqa: ANN001, ANN002, ANN003
        calls.append(("proc", list(cmd)))
        return types.SimpleNamespace(returncode=0)

    monkeypatch.setattr(MOD.subprocess, "run", _fake_run)
    return calls


class _SharedListHandler(logging.Handler):
    """Logging handler that appends ``("log", message)`` to a shared list."""

    def __init__(self, sink: list) -> None:
        super().__init__(level=logging.INFO)
        self.sink = sink

    def emit(self, record: logging.LogRecord) -> None:
        """Append the formatted message to the shared sink."""
        self.sink.append(("log", record.getMessage()))


def _materialize(
    repo_root: Path,
    *,
    csv_name: str = "mydataset.csv",
    run_id: str = "mydataset",
    force: bool = False,
    template: Path | None = None,
    allow_bare_config: bool = False,
) -> Path:
    """Call ``materialize_config`` with fake-repo-consistent arguments.

    ``csv_path`` is absolute under the fake root (so ``relative_to(REPO_ROOT)``
    yields ``data/<name>``) and ``run_dir`` is RELATIVE (``runs/<run_id>``),
    matching how ``run_dataset`` constructs both.
    """
    return MOD.materialize_config(
        csv_path=repo_root / "data" / csv_name,
        run_dir=Path("runs") / run_id,
        run_id=run_id,
        force=force,
        template=template,
        allow_bare_config=allow_bare_config,
    )


def _digest_line(messages: list[str], dotted: str) -> str:
    """Return the key-settings digest line for ``dotted`` from log messages."""
    matches = [m for m in messages if m.strip().startswith(dotted + " ")]
    assert matches, f"no digest line for {dotted!r} in {messages}"
    return matches[0]


