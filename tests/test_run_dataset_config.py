"""
Tests for orchestrator per-run config materialisation (``scripts/run_dataset.py``).

Regression guard for the defect documented in ``specs/30`` §1.4: the
``--config-template`` flag was parsed and discarded, so ``materialize_config``
always wrote a hard-coded two-key overlay (``data.csv_path`` + ``run.dir``).
Because ``src/utils/config.py::load_config`` deep-merges the experiment file
over ``configs/default.yaml``, every tuned balancer / model / reproducibility
setting silently reverted to the defaults — which already produced one on-disk
run with the wrong class weights.

Implementation contract under test: ``specs/31`` §I.2 (precedence),
§I.3 (helpers, guard, ``materialize_config``), §I.4 (``log_resolved_config``),
§I.5 (``--force-config`` refusal), §I.6 (refuse, never auto-heal).

Three hard rules honoured here (``specs/31`` §I.8.1):
  1. Artifact-free and in the default ``pytest tests/ -v`` gate — ``tmp_path``
     + ``yaml`` + ``load_config`` + ``materialize_config`` only. No
     ``feature_store/``, no ``graphs/``, no checkpoint, no skip guard.
  2. Never write into the real ``configs/``. Every writing test builds a
     throwaway repo root under ``tmp_path`` and monkeypatches the module's
     ``REPO_ROOT`` (which also redirects ``run_dataset``'s ``runs/<id>/``
     mkdir). The only touch of the real checkout is the read-only verdict
     table in test 10b.
  3. Assert on values loaded through the REAL ``load_config``, not on file
     text, wherever the claim is about settings — structural text assertions
     do not prove a value survives the merge with ``default.yaml``, which is
     the entire bug.

Tests (numbering follows ``specs/31`` §I.8.3):

Group A — template merge (devops 1, 5)
   1 — tuned template values survive into the loaded config (regression anchor).
   2 — run paths AND tuned values coexist in ONE generated file.
   3 — precedence is default.yaml < template < injection.
   4 — a missing template path aborts and writes nothing.
   5 — a non-mapping template aborts, naming the parsed type.
   6 — an empty template yields a bare result and trips the guard, before any
       write (nothing is left on disk).
  6b — ``force`` + a stub-shaped template does NOT destroy an existing tuned
       config: the guard refuses before the write (stage-4 ordering defect).

Group B — the bare-stub guard (devops 3, 4)
   7 — a pre-existing bare stub aborts ``run_dataset`` before phase 01.
   8 — the guard does NOT auto-heal: the file stays byte-identical.
   9 — ``allow_bare_config`` suppresses the refusal, with a warning.
  10 — a ``{data, run, seed}`` starter shape does not trip the guard.
 10b — the REAL on-disk Paper-3 configs each get their expected verdict.
  11 — a 7-key tuned config shape does not trip the guard (HPC configs).
  12 — the no-template write is exempt and survives re-invocation.
  13 — stripping the acknowledgement marker re-arms the guard (fail-closed).
  14 — the legacy auto-generated header alone does not exempt.
  15 — ``_top_level_keys`` / ``_has_no_template_marker`` unit behaviour.

Group C — existing files and ``--force-config``
  16 — an existing config wins over a supplied template (HPC flow).
  17 — ``force`` + template rewrites from the template.
  18 — ``force`` without a template refuses and does not truncate.
  19 — ``force`` without a template cannot launder an existing stub.
  20 — ``force`` without a template on a missing file is allowed.
  21 — the fresh no-template write warns, naming the defaults actually taken.

Group D — the pre-phase inspection (devops 2)
  22 — the resolved config is logged BEFORE any phase subprocess (ordering).
  23 — the logging notes the ``run.dir``-prefixing caveat.
  24 — the key-settings digest marks absent keys, and distinguishes ``None``.
"""

