def test_empty_template_trips_the_bare_stub_guard(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Devops 3 — a zero-byte template yields a bare result and refuses.

    ``yaml.safe_load`` returns ``None`` for an empty document, so the merged
    result is the two-key injection alone; the guard catches it with a far more
    useful message than a parse error would give.

    The refusal happens BEFORE the write (the guard runs on the in-memory
    merged mapping), so the promise the message itself makes — "Nothing was
    modified on disk" — is asserted here, not just the raise: no config file
    may exist afterwards.
    """
    repo_root, configs_dir = _fake_repo(tmp_path, monkeypatch)
    tpl = tmp_path / "empty.yaml"
    tpl.write_text("")

    with pytest.raises(MOD.ConfigMaterializationError) as excinfo:
        _materialize(repo_root, template=tpl)

    assert "Nothing was modified on disk" in str(excinfo.value)
    assert not (configs_dir / "experiment_mydataset.yaml").exists()


def test_force_config_with_a_stub_shaped_template_does_not_destroy_a_tuned_config(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Devops 3 — the destructive path: ``--force-config`` + a bare template.

    Regression anchor for the write-ordering defect found at stage 4. The guard
    used to run only AFTER ``cfg_path.write_text``, so this exact invocation
    replaced a real 7-key tuned config on disk with a two-key stub and only
    then raised — with a message claiming nothing had been modified. The guard
    now judges the in-memory merged mapping, so the existing file must be
    byte-identical after the refusal.
    """
    repo_root, configs_dir = _fake_repo(tmp_path, monkeypatch)
    cfg_file = configs_dir / "experiment_mydataset.yaml"
    _seven_key_config(cfg_file)
    before = cfg_file.read_bytes()
    tpl = tmp_path / "empty.yaml"
    tpl.write_text("")

    with pytest.raises(MOD.ConfigMaterializationError) as excinfo:
        _materialize(repo_root, force=True, template=tpl)

    assert "Nothing was modified on disk" in str(excinfo.value)
    assert cfg_file.read_bytes() == before
    assert set(yaml.safe_load(cfg_file.read_text())) != {"data", "run"}


