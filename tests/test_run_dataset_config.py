def test_preexisting_bare_stub_aborts_before_phase_01(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Devops 3, 4 — refusal precedes any compute.

    The verbatim damaged ``configs/experiment_nf_unsw_nb15_v3.yaml`` is placed
    in the fake configs dir, ``run_dataset`` is invoked with ``from_phase=1``,
    and the run must return *False* with the subprocess recorder EMPTY — i.e.
    not a single phase script was launched.
    """
    repo_root, configs_dir = _fake_repo(tmp_path, monkeypatch)
    (configs_dir / "experiment_nf_unsw_nb15_v3.yaml").write_text(LEGACY_STUB_TEXT)
    calls = _no_subprocess(monkeypatch)

    ok = MOD.run_dataset(
        csv_path=repo_root / "data" / "NF-UNSW-NB15-v3.csv",
        dataset_index=1,
        total_datasets=1,
        from_phase=1,
        to_phase=14,
        skip_tests=True,
        skip_gateway_distance=False,
        force_config=False,
    )

    assert ok is False
    assert calls == []


def test_preexisting_bare_stub_is_not_auto_healed(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Devops 3 — the guard refuses; it never rewrites (specs/31 §I.6).

    Even with a tuned template available to "heal" from, the pre-existing file
    must be byte-identical afterwards. Pins the refuse-not-auto-heal decision
    so a future change cannot quietly convert it into a rewrite that clobbers a
    deliberately-minimal hand-written config (these files are untracked, so
    there is no ``git checkout`` recovery).
    """
    repo_root, configs_dir = _fake_repo(tmp_path, monkeypatch)
    cfg_file = configs_dir / "experiment_mydataset.yaml"
    cfg_file.write_text(LEGACY_STUB_TEXT)
    before = cfg_file.read_bytes()
    tpl = tmp_path / "tuned.yaml"
    _tuned_template(tpl)

    with pytest.raises(MOD.ConfigMaterializationError):
        _materialize(repo_root, template=tpl)

    assert cfg_file.read_bytes() == before


def test_allow_bare_config_suppresses_the_guard_with_a_warning(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, caplog: pytest.LogCaptureFixture
) -> None:
    """Devops 3 — the escape hatch downgrades the refusal to a WARNING."""
    repo_root, configs_dir = _fake_repo(tmp_path, monkeypatch)
    cfg_file = configs_dir / "experiment_mydataset.yaml"
    cfg_file.write_text(LEGACY_STUB_TEXT)

    caplog.set_level(logging.INFO, logger="run_dataset")
    returned = _materialize(repo_root, allow_bare_config=True)

    assert returned == cfg_file
    warnings = [
        r.getMessage() for r in caplog.records if r.levelno >= logging.WARNING
    ]
    assert any("--allow-bare-config" in m for m in warnings)


